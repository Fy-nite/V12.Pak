using System.Text.Json;

namespace V12.Pak
{
    /// <summary>
    /// Builds a <c>.v12pak</c> from a directory of game content. The directory
    /// layout mirrors the archive layout:
    ///
    /// <code>
    /// input/
    ///   manifest.json            (optional — regenerated when absent)
    ///     worlds/{World}/world.xml
    ///     worlds/{World}/templates/*.xml
    ///     assets/**                (textures, meshes, scripts, ...)
    ///     paks/*.dll
    ///     scripts/*.ct             (Contract gamepack entrypoints)
    ///     scripts/*.cs             (C# component sources, compiled at load time)
    ///     dependencies/*.v12pak    (paks this one depends on)
    /// </code>
    ///
    /// When no manifest.json is present, one is generated by scanning the
    /// directory: worlds/ subdirectories that contain a world.xml (or main.xml)
    /// become world entries, files under assets/ become asset-map entries, files
    /// under paks/ become the pak DLL list, files under scripts/ become the
    /// Contract script and C# source lists, and .v12pak files under
    /// dependencies/ become the dependency list.
    /// </summary>
    public static class V12PakBuilder
    {
        /// <summary>
        /// Pack <paramref name="inputDirectory"/> using its own
        /// <c>manifest.json</c> when present, or an auto-generated manifest when
        /// it is not.
        /// </summary>
        public static void Build(string inputDirectory, string outputPath)
        {
            ValidateInputDirectory(inputDirectory);
            Build(inputDirectory, outputPath, ReadOrBuildManifest(inputDirectory));
        }

        /// <summary>
        /// Pack <paramref name="inputDirectory"/> using exactly
        /// <paramref name="manifest"/> (no auto-detection). Referenced entries
        /// are validated against the input directory before packing.
        /// </summary>
        public static void Build(string inputDirectory, string outputPath, V12PakManifest manifest)
        {
            ValidateInputDirectory(inputDirectory);
            ArgumentNullException.ThrowIfNull(manifest);

            ValidateManifest(inputDirectory, manifest);

            using var writer = new V12PakWriter(outputPath);
            writer.WriteManifest(manifest);
            WriteAllFiles(writer, inputDirectory, outputPath, manifest);
        }

        /// <summary>
        /// Pack <paramref name="inputDirectory"/> using the manifest read from
        /// <paramref name="manifestPath"/> (absolute, or relative to the input
        /// directory). This is the entry point behind <c>vcsdk build --manifest</c>.
        /// </summary>
        public static void Build(string inputDirectory, string outputPath, string manifestPath)
        {
            ValidateInputDirectory(inputDirectory);

            string resolved = Path.IsPathRooted(manifestPath)
                ? manifestPath
                : Path.Combine(inputDirectory, manifestPath);

            if (!File.Exists(resolved))
                throw new FileNotFoundException($"Manifest file not found: {resolved}", resolved);

            Build(inputDirectory, outputPath, LoadManifest(resolved));
        }

        /// <summary>Read a manifest.json from disk (case-insensitive keys, comments and trailing commas allowed).</summary>
        public static V12PakManifest LoadManifest(string manifestPath)
        {
            using var stream = File.OpenRead(manifestPath);
            return JsonSerializer.Deserialize<V12PakManifest>(stream, new JsonSerializerOptions
                   {
                       PropertyNameCaseInsensitive = true,
                       ReadCommentHandling = JsonCommentHandling.Skip,
                       AllowTrailingCommas = true,
                   })
                   ?? throw new InvalidDataException($"Manifest is empty or invalid: {manifestPath}");
        }

        private static void ValidateInputDirectory(string inputDirectory)
        {
            if (!Directory.Exists(inputDirectory))
                throw new DirectoryNotFoundException($"Input directory not found: {inputDirectory}");
        }

        /// <summary>
        /// Verify every archive path the manifest points at actually exists in
        /// <paramref name="inputDirectory"/> so a typo fails the build instead of
        /// producing a pak that loads an empty world or skips a script.
        /// </summary>
        private static void ValidateManifest(string inputDirectory, V12PakManifest manifest)
        {
            var missing = new List<string>();
            string root = Path.GetFullPath(inputDirectory);

            void CheckFile(string archivePath, string role)
            {
                if (string.IsNullOrWhiteSpace(archivePath)) return;
                string diskPath = ResolveCaseInsensitive(root, archivePath);
                if (diskPath == null || !File.Exists(diskPath)) missing.Add($"{role}: '{archivePath}'");
            }

            foreach (var world in manifest.Worlds)
            {
                CheckFile(world.Entry, $"world '{world.Name}'");
                if (!string.IsNullOrWhiteSpace(world.TemplatesDir))
                {
                    string templates = ResolveCaseInsensitive(root, world.TemplatesDir);
                    if (templates == null || !Directory.Exists(templates))
                        missing.Add($"templates for world '{world.Name}': '{world.TemplatesDir}'");
                }
            }

            foreach (var asset in manifest.Assets.Values)
                CheckFile(asset, "asset");
            foreach (var pak in manifest.Paks)
                CheckFile(pak, "pak DLL");
            foreach (var script in manifest.Scripts)
                CheckFile(script, "script");
            foreach (var script in manifest.CSharpScripts)
                CheckFile(script, "C# script");

            if (missing.Count > 0)
            {
                throw new FileNotFoundException(
                    $"Manifest references {missing.Count} file(s) that are not in '{inputDirectory}':\n  " +
                    string.Join("\n  ", missing));
            }
        }

        /// <summary>
        /// Resolve an archive path to a physical path under <paramref name="root"/>,
        /// matching each segment case-insensitively (manifests are often written on
        /// Windows with different casing than the files).
        /// </summary>
        private static string? ResolveCaseInsensitive(string root, string archivePath)
        {
            string current = root;
            foreach (string segment in archivePath.Replace('\\', '/').Split('/', StringSplitOptions.RemoveEmptyEntries))
            {
                if (segment == ".") continue;
                string candidate = Path.Combine(current, segment);
                if (File.Exists(candidate) || Directory.Exists(candidate))
                {
                    current = candidate;
                    continue;
                }

                string? match = null;
                if (Directory.Exists(current))
                {
                    match = Directory.EnumerateFileSystemEntries(current)
                        .FirstOrDefault(p => string.Equals(Path.GetFileName(p), segment, StringComparison.OrdinalIgnoreCase));
                }
                if (match == null) return null;
                current = match;
            }
            return current;
        }

        private static V12PakManifest ReadOrBuildManifest(string inputDirectory)
        {
            string manifestPath = Path.Combine(inputDirectory, "manifest.json");
            if (File.Exists(manifestPath))
                return LoadManifest(manifestPath);

            var manifest = new V12PakManifest { Version = 1, Engine = "v12" };

            string worldsDir = Path.Combine(inputDirectory, "worlds");
            if (Directory.Exists(worldsDir))
            {
                foreach (var worldDir in Directory.GetDirectories(worldsDir))
                {
                    string name = Path.GetFileName(worldDir);
                    string entry = null!;
                    foreach (var candidate in new[] { "world.xml", "main.xml" })
                    {
                        if (File.Exists(Path.Combine(worldDir, candidate)))
                        {
                            entry = $"worlds/{name}/{candidate}";
                            break;
                        }
                    }
                    if (entry == null) continue;

                    string templatesDir = Path.Combine(worldDir, "templates");
                    manifest.Worlds.Add(new V12PakWorldEntry
                    {
                        Name = name,
                        Entry = entry,
                        TemplatesDir = Directory.Exists(templatesDir) ? $"worlds/{name}/templates/" : ""
                    });
                }
            }

            string assetsDir = Path.Combine(inputDirectory, "assets");
            if (Directory.Exists(assetsDir))
            {
                foreach (var file in Directory.EnumerateFiles(assetsDir, "*", SearchOption.AllDirectories))
                {
                    string relative = Path.GetRelativePath(assetsDir, file).Replace('\\', '/');
                    manifest.Assets[relative] = $"assets/{relative}";
                }
            }

            string paksDir = Path.Combine(inputDirectory, "paks");
            if (Directory.Exists(paksDir))
            {
                foreach (var file in Directory.EnumerateFiles(paksDir, "*.dll", SearchOption.AllDirectories))
                {
                    manifest.Paks.Add(Path.GetRelativePath(inputDirectory, file).Replace('\\', '/'));
                }
            }

            string scriptsDir = Path.Combine(inputDirectory, "scripts");
            if (Directory.Exists(scriptsDir))
            {
                foreach (var pattern in new[] { "*.ct", "*.orbt", "*.oil" })
                    foreach (var file in Directory.EnumerateFiles(scriptsDir, pattern, SearchOption.AllDirectories))
                    {
                        string relative = Path.GetRelativePath(inputDirectory, file).Replace('\\', '/');
                        if (!manifest.Scripts.Contains(relative))
                            manifest.Scripts.Add(relative);
                    }

                foreach (var file in Directory.EnumerateFiles(scriptsDir, "*.cs", SearchOption.AllDirectories))
                {
                    string relative = Path.GetRelativePath(inputDirectory, file).Replace('\\', '/');
                    if (!manifest.CSharpScripts.Contains(relative))
                        manifest.CSharpScripts.Add(relative);
                }
            }

            // Dependency paks are embedded in the archive so it stays a single
            // distributable file; the loader extracts them alongside the rest.
            string dependenciesDir = Path.Combine(inputDirectory, "dependencies");
            if (Directory.Exists(dependenciesDir))
            {
                foreach (var file in Directory.EnumerateFiles(dependenciesDir, "*.v12pak", SearchOption.AllDirectories))
                {
                    string relative = Path.GetRelativePath(inputDirectory, file).Replace('\\', '/');
                    if (!manifest.Dependencies.Contains(relative))
                        manifest.Dependencies.Add(relative);
                }
            }

            return manifest;
        }

        private static void WriteAllFiles(V12PakWriter writer, string inputDirectory, string outputPath, V12PakManifest manifest)
        {
            string outputFullPath = Path.GetFullPath(outputPath);

            foreach (var file in Directory.EnumerateFiles(inputDirectory, "*", SearchOption.AllDirectories))
            {
                string relative = Path.GetRelativePath(inputDirectory, file).Replace('\\', '/');
                if (string.Equals(relative, "manifest.json", StringComparison.OrdinalIgnoreCase)) continue;
                if (string.Equals(Path.GetFullPath(file), outputFullPath, StringComparison.OrdinalIgnoreCase)) continue;
                if (string.Equals(Path.GetExtension(relative), ".v12pak", StringComparison.OrdinalIgnoreCase)
                    && !IsManifestDependency(manifest, relative))
                    continue;
                writer.AddFile(relative, file);
            }
        }

        /// <summary>
        /// Dependency paks are the only <c>.v12pak</c> files that belong inside a
        /// pak (the loader resolves and extracts them). Any other archive found
        /// in the input directory — e.g. a previous build under <c>bin/</c> — is
        /// skipped so paks cannot accidentally nest themselves.
        /// </summary>
        private static bool IsManifestDependency(V12PakManifest manifest, string relativePath)
        {
            string normalized = relativePath.Replace('\\', '/');
            if (normalized.StartsWith("dependencies/", StringComparison.OrdinalIgnoreCase)) return true;

            foreach (string dependency in manifest.Dependencies)
            {
                if (string.Equals(dependency.Replace('\\', '/').TrimStart('/'), normalized, StringComparison.OrdinalIgnoreCase))
                    return true;
            }
            return false;
        }
    }
}
